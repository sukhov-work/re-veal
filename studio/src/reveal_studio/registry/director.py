def R(
    key: str,
    table: str,
    typ: str,
    default: Any,
    *,
    default_from: str,
    read_at: str,
    when: str,
    what: str,
    source: str,
    plan_path: str | None = None,
    choices: list[Any] | None = None,
    rng: list[float] | None = None,
    kinds: dict[str, Any] | None = None,
    readonly: str | None = None,
    scope: str | None = None,
) -> dict[str, Any]:
    """One row of the `--set` table. `scope` global (a top-level key), sky (`sky.<key>`) or transform
    (`<name>.<key>`); `set_key` is the key as the `set` dict and the argv carry it (`<name>` stands for the transform's
    name); `hint` its key in registry/hints_director.py; `kinds` (table C) the code's default per transform kind."""
    scope = scope or {"A": "global", "B": "sky", "C": "transform"}[table]
    set_key = {"global": key, "sky": f"sky.{key}", "transform": f"<name>.{key}"}[scope]
    hint = {"global": f"set.{key}", "sky": f"set.sky.{key}", "transform": f"set.tr.{key}"}[scope]
    return {
        "key": key,
        "table": table,
        "scope": scope,
        "set_key": set_key,
        "hint": hint,
        "type": typ,
        "default": default,
        "default_from": default_from,
        "read_at": read_at,
        "when": when,
        "plan_path": plan_path,
        "what": what,
        "source": source,
        "choices": choices,
        "range": rng,
        "kinds": kinds,
        "readonly": readonly,
    }


