SET_KEYS: list[dict[str, Any]] = TABLE_A + TABLE_B + TABLE_C + TABLE_D
"""The renderer's `--set` table: 26 + 18 + 60 keys that change a render, and the 8 of table D that change nothing."""
GLOBAL_KEYS: dict[str, dict[str, Any]] = {r["key"]: r for r in SET_KEYS if r["scope"] == "global"}
SKY_KEYS: dict[str, dict[str, Any]] = {r["key"]: r for r in SET_KEYS if r["scope"] == "sky"}
TRANSFORM_KEYS: dict[str, dict[str, Any]] = {r["key"]: r for r in SET_KEYS if r["scope"] == "transform"}


def set_key_problem(key: str, transforms: list[str]) -> str | None:
    """Why a `--set` key reaches no frame for a concept whose transforms are named `transforms`, or None. The renderer
    reads the 28 top-level keys by name, a `sky.<key>` among the 18 sky keys, and a `<name>.<key>` when a transform is
    so named (D:881-889, D:1439-1441); everything else it stores and never reads, and table D's keys it reads too
    early or never. A transform's other params stay open: the renderer passes any key to the transform."""
    head, dot, rest = key.partition(".")
    if not dot:
        row = GLOBAL_KEYS.get(key)
        if row is None:
            return f"{key} is a key director_render.py never reads (its top-level keys are the table's {len(GLOBAL_KEYS)} rows)"
        return f"{key} reaches no frame: {row['readonly']}" if row["readonly"] else None
    if head == "sky":
        row = SKY_KEYS.get(rest)
        if row is None:
            return (
                f"{key} is a sky key director_render.py never reads (the sky keys are the table's {len(SKY_KEYS)} rows)"
            )
        return f"{key} reaches no frame: {row['readonly']}" if row["readonly"] else None
    if head not in transforms:
        named = ", ".join(transforms) or "none"
        return (
            f"{key} names no transform of the concept (its transforms: {named}), so director_render.py never reads it"
        )
    row = TRANSFORM_KEYS.get(rest)
    if row is not None and row["readonly"]:
        return f"{key} reaches no frame: {row['readonly']}"
    return None


